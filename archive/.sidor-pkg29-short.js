    function useSessionFace(sessionId) {
      const [face, setFace] = React.useState(null)
      React.useEffect(() => {
        let f = null
        if (sessionId && sessionsSvc) {
          try { const b = sessionsSvc.binding(sessionId); if (b && b.session) f = b.session } catch (e) { /* ignore */ }
        }
        setFace(f || null)
      }, [sessionId])
      return face
    }

    function useSessionSnap(face) {
      const [snap, setSnap] = React.useState(null)
      React.useEffect(() => {
        if (!face) { setSnap(null); return }
        let alive = true
        const sync = () => { if (alive) { try { setSnap(face.getSnapshot()) } catch (e) { /* ignore */ } } }
        sync()
        let off = null
        try { off = face.subscribe(sync) } catch (e) { /* ignore */ }
        return () => { alive = false; if (off) { try { off() } catch (e) { /* ignore */ } } }
      }, [face])
      return snap
    }

    /* subscribe one session projection value (key → value | null) */
    function useProjection(face, key) {
      const [value, setValue] = React.useState(null)
      React.useEffect(() => {
        if (!face) { setValue(null); return }
        let alive = true
        let off = null
        const read = () => {
          if (!alive) return
          try {
            const f = face.projections.faceOf(key)
            if (!f) { setValue(null); return }
            const v = f.getSnapshot()
            setValue(v === undefined ? null : v)
            if (!off) off = f.subscribe(() => read())
          } catch (e) { setValue(null) }
        }
        read()
        return () => { alive = false; if (off) { try { off() } catch (e) { /* ignore */ } } }
      }, [face, key])
      return value
    }

    function useProjSvc(sessionId) {
      const face = useSessionFace(sessionId)
      return face
    }

