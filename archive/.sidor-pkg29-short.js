    function blocksText(blocks) {
      if (!Array.isArray(blocks)) return ''
      const parts = []
      for (const b of blocks) {
        if (!b) continue
        if ((b.type === 'text' || b.kind === 'text') && typeof b.text === 'string' && b.text.trim() !== '') parts.push(b.text)
        else if (b.type === 'image' || b.kind === 'image') parts.push('[' + (zh ? '图片' : 'image') + ']')
        else if (b.type === 'tool-call' || b.kind === 'tool-call') parts.push('⚙ ' + (b.name || 'tool'))
      }
      return parts.join('\n')
    }

    function historyRow(node) {
      const d = node && node.data
      if (!d) return null
      if (node.kind === 'user') {
        const text = blocksText(d.content)
        return text ? { kind: 'user', text: text } : null
      }
      if (node.kind === 'assistant-step') {
        const blocks = d.finalNode ? d.finalNode.blocks : d.blocks
        const text = blocksText(blocks)
        if (d.status === 'running') return { kind: 'typing', text: text || '…' }
        return text ? { kind: 'assistant', text: text } : null
      }
      if (node.kind === 'command') {
        const args = d.args
        const line = d.name ? '/' + d.name + (args ? ' ' + (typeof args === 'string' ? args : '') : '') : ''
        return line ? { kind: 'cmd', text: line } : null
      }
      return null
    }

    function HistoryView(props) {
      const { sessionId } = props
      const face = useSessionFace(sessionId)
      const snap = useSessionSnap(face)
      const ref = React.useRef(null)
      const chat = snap && snap.chat
      const order = chat && Array.isArray(chat.order) ? chat.order : []
      const nodes = chat && chat.nodes ? chat.nodes : null
      const rows = []
      if (nodes) {
        for (const key of order) {
          const row = historyRow(nodes.get(key))
          if (row) rows.push({ key: key, kind: row.kind, text: row.text })
        }
      }
      const count = rows.length
      React.useEffect(() => {
        const el = ref.current
        if (el) el.scrollTop = el.scrollHeight
      }, [count, !!(snap && snap.running)])
      if (count === 0) return null
      return React.createElement('div', { ref: ref, className: 'sid-history', 'aria-label': zh ? '对话历史' : 'History' },
        rows.map((r) => React.createElement('div', {
          key: r.key,
          className: 'sid-msg ' + r.kind,
        }, r.text)),
      )
    }

